-- Generates figure_skills.lua: for every character skill tree of the game, which upgrade each bit of
-- a figure's saved skill bits stands for, and the name that upgrade has in the skill-tree grid.
-- Run with a Lua 5.1 interpreter, gamedb file paths on stdin (compiled gamedb/core in1_/in2_/in3_*.lua):
--   ls .../gamedb/core/core/core/in[123]_*.lua | crabe_lua gen_figure_skills.lua > ../figure_skills.lua
local trees = {}
for path in io.lines() do
    local f = io.open(path, "rb")
    if f then
        local data = f:read("*a")
        f:close()
        local chunk = loadstring(data)
        if chunk then
            local env = setmetatable({}, { __index = function(_, k) return _G[k] or function() return {} end end })
            setfenv(chunk, env)
            if pcall(chunk) and type(env.ProgressionTable) == "table" then
                local t = env.ProgressionTable
                if type(t.Name) == "string" and type(t.BitMap) == "table" then
                    local bits = {}
                    for key, entry in pairs(t.BitMap) do
                        local n = tonumber(tostring(key):match("^BIT(%d+)$"))
                        if n and type(entry) == "table" and type(entry.Upgrade) == "string" then
                            local upgrade = (t.Upgrades or {})[entry.Upgrade]
                            bits[n] = { entry.Upgrade, type(upgrade) == "table" and upgrade.UpgradeName or nil }
                        end
                    end
                    trees[t.Name] = bits
                end
            end
        end
    end
end

local names = {}
for name in pairs(trees) do names[#names + 1] = name end
table.sort(names)
io.write("-- Generated by tools/gen_figure_skills.lua from the game's gamedb; do not edit.\n")
io.write("-- [ProgressionTree] = { [bit] = { upgrade, gridName } }\n")
io.write("return {\n")
for _, name in ipairs(names) do
    io.write(string.format("    [%q] = {", name))
    local bits = {}
    for n in pairs(trees[name]) do bits[#bits + 1] = n end
    table.sort(bits)
    for _, n in ipairs(bits) do
        local b = trees[name][n]
        io.write(string.format(" [%d] = { %q%s },", n, b[1], b[2] and string.format(", %q", b[2]) or ""))
    end
    io.write(" },\n")
end
io.write("}\n")
